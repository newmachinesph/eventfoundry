# ─── 4. Embedding helpers ─────────────────────────────────────────────────────

def get_embedding(text: str) -> list[float]:
    """Returns a 1536-dimensional embedding from OpenAI text-embedding-3-small."""
    response = openai_client.embeddings.create(
        input=text,
        model="text-embedding-3-small",
    )
    return response.data[0].embedding


def venue_embed_text(venue: dict) -> str:
    return (
        f"Name: {venue['name']}\n"
        f"Region: {venue['region']}\n"
        f"Type: {', '.join(venue['venue_type'])}\n"
        f"Capacity: up to {venue['max_capacity']} guests\n"
        f"Price: SGD {venue['min_pax_price']:.0f} per pax, "
        f"estimated total SGD {venue['est_total_price']:.0f}\n"
        f"Description: {venue['description']}"
    )


def vendor_embed_text(vendor: dict) -> str:
    return (
        f"Name: {vendor['name']}\n"
        f"Category: {vendor['category']}\n"
        f"Specialties: {', '.join(vendor['specialties'])}\n"
        f"Starting price: SGD {vendor['base_price']:.0f}\n"
        f"Description: {vendor['description']}"
    )


def format_embedding(vector: list[float]) -> str:
    """Formats a float list as a pgvector-compatible string '[x, y, z, ...]'."""
    return "[" + ",".join(map(str, vector)) + "]"


# ─── 5. Seed functions ────────────────────────────────────────────────────────

def seed_venues():
    print(f"\n{'─' * 50}")
    print(f"Seeding {len(VENUES)} venues…")
    print(f"{'─' * 50}")

    for i, venue in enumerate(VENUES, 1):
        print(f"[{i:02d}/{len(VENUES)}] {venue['name']} ({venue['region']})")

        try:
            print(f"       Generating embedding…")
            vector = get_embedding(venue_embed_text(venue))

            payload = venue.copy()
            payload["embedding"] = format_embedding(vector)

            supabase.table("venues").upsert(payload, on_conflict="slug").execute()
            print(f"       ✅ Upserted\n")

            # Respect OpenAI rate limits (3 RPM on free tier, 500 RPM on paid)
            time.sleep(0.2)

        except Exception as e:
            print(f"       ❌ Error: {e}\n")


def seed_vendors():
    print(f"\n{'─' * 50}")
    print(f"Seeding {len(VENDORS)} vendors…")
    print(f"{'─' * 50}")

    for i, vendor in enumerate(VENDORS, 1):
        print(f"[{i:02d}/{len(VENDORS)}] {vendor['name']} ({vendor['category']})")

        try:
            print(f"       Generating embedding…")
            vector = get_embedding(vendor_embed_text(vendor))

            payload = vendor.copy()
            payload["embedding"] = format_embedding(vector)

            supabase.table("vendors").upsert(payload, on_conflict="slug").execute()
            print(f"       ✅ Upserted\n")

            time.sleep(0.2)

        except Exception as e:
            print(f"       ❌ Error: {e}\n")


